using System.Net.Http.Headers;
using System.Net.Http.Json;
using System.Text.Json;
using Google.Apis.Auth.OAuth2;
using Microsoft.Extensions.Logging;
using Microsoft.Extensions.Options;
using Polly.CircuitBreaker;
using ReadIn.Infrastructure.Identity;

namespace ReadIn.Infrastructure.Realtime;

/// <summary>
/// Writes to the Firebase Realtime Database through its REST API (the .NET Admin SDK has no RTDB client), SPEC §21.2.
/// Shared by the live publisher and the media status signals. Best effort: retries and the circuit breaker come from
/// the HTTP pipeline (<see cref="RealtimeRegistration"/>), and a write that still fails is logged and never reaches the
/// caller, because clients keep working through REST without live signals.
/// </summary>
internal sealed partial class RealtimeDatabaseClient(
    HttpClient http,
    IOptions<FirebaseOptions> options,
    IRealtimeDatabaseCredential credential,
    ILogger<RealtimeDatabaseClient> logger)
{
    /// <summary>Stored by RTDB as its own clock in epoch ms when it applies the write.</summary>
    public static readonly IReadOnlyDictionary<string, string> ServerTimestamp = new Dictionary<string, string> { [".sv"] = "timestamp" };

    /// <summary>The emulator treats this bearer token as an admin that bypasses the security rules.</summary>
    private const string EmulatorAdminToken = "owner";

    /// <summary>Replaces the value at <paramref name="path"/>.</summary>
    public Task<bool> PutAsync(string path, object? value, CancellationToken cancellationToken) =>
        SendAsync(HttpMethod.Put, path, value, cancellationToken);

    /// <summary>Replaces only the given children of <paramref name="path"/>; the others (e.g. <c>events</c>) are kept.</summary>
    public Task<bool> PatchAsync(string path, object value, CancellationToken cancellationToken) =>
        SendAsync(HttpMethod.Patch, path, value, cancellationToken);

    /// <summary>Adds a child under <paramref name="path"/> with a chronological push id generated by RTDB.</summary>
    public Task<bool> PostAsync(string path, object value, CancellationToken cancellationToken) =>
        SendAsync(HttpMethod.Post, path, value, cancellationToken);

    /// <summary>Deletes the given children of <paramref name="path"/> in one multi-location update (null removes a child).</summary>
    public Task<bool> DeleteChildrenAsync(string path, IReadOnlyCollection<string> keys, CancellationToken cancellationToken) =>
        keys.Count == 0 ? Task.FromResult(true) : PatchAsync(path, keys.ToDictionary(k => k, _ => (object?)null), cancellationToken);

    /// <summary>
    /// The child keys of <paramref name="path"/> (a shallow read: values aren't downloaded); empty when there are none,
    /// null when RTDB isn't configured or the read failed. Used by the cleanup job only.
    /// </summary>
    public async Task<IReadOnlyList<string>?> GetKeysAsync(string path, CancellationToken cancellationToken)
    {
        if (options.Value.RealtimeDatabaseBaseUrl is null) return null;
        try
        {
            using var request = await RequestAsync(HttpMethod.Get, path, "shallow=true", cancellationToken);
            using var response = await http.SendAsync(request, cancellationToken);
            if (!response.IsSuccessStatusCode)
            {
                LogRejected(logger, "GET", path, (int)response.StatusCode);
                return null;
            }

            var keys = await response.Content.ReadFromJsonAsync<Dictionary<string, JsonElement>?>(cancellationToken);
            return keys is null ? [] : [.. keys.Keys];
        }
        catch (BrokenCircuitException)
        {
            LogCircuitOpen(logger, "GET", path);
            return null;
        }
        catch (Exception ex) when (!cancellationToken.IsCancellationRequested)
        {
            LogFailed(logger, ex, "GET", path);
            return null;
        }
    }

    private async Task<HttpRequestMessage> RequestAsync(HttpMethod method, string path, string? query, CancellationToken cancellationToken)
    {
        var firebase = options.Value;
        // The emulator keeps one database per namespace; the clients connect to `demo-readin` too.
        string[] parameters = [.. new[] { query, firebase.UseEmulator ? $"ns={Uri.EscapeDataString(firebase.ProjectId)}" : null }.OfType<string>()];
        var url = $"{firebase.RealtimeDatabaseBaseUrl}/{path}.json" + (parameters.Length > 0 ? "?" + string.Join('&', parameters) : string.Empty);

        var request = new HttpRequestMessage(method, url);
        request.Headers.Authorization = new AuthenticationHeaderValue("Bearer", firebase.UseEmulator
            ? EmulatorAdminToken
            : await credential.GetAccessTokenAsync(cancellationToken));
        return request;
    }

    private async Task<bool> SendAsync(HttpMethod method, string path, object? value, CancellationToken cancellationToken)
    {
        if (options.Value.RealtimeDatabaseBaseUrl is null) return false;

        try
        {
            using var request = await RequestAsync(method, path, query: null, cancellationToken);
            // Bytes rather than a JsonContent stream, so a retry can send the same body again.
            request.Content = new ByteArrayContent(JsonSerializer.SerializeToUtf8Bytes(value));
            request.Content.Headers.ContentType = new MediaTypeHeaderValue("application/json");

            using var response = await http.SendAsync(request, cancellationToken);
            if (response.IsSuccessStatusCode) return true;

            LogRejected(logger, method.Method, path, (int)response.StatusCode);
            return false;
        }
        catch (BrokenCircuitException)
        {
            LogCircuitOpen(logger, method.Method, path);
            return false;
        }
        catch (Exception ex) when (!cancellationToken.IsCancellationRequested)
        {
            LogFailed(logger, ex, method.Method, path);
            return false;
        }
    }

    [LoggerMessage(Level = LogLevel.Warning, Message = "Realtime Database rejected {Method} {Path} with HTTP {Status}; clients stay on REST")]
    private static partial void LogRejected(ILogger logger, string method, string path, int status);

    [LoggerMessage(Level = LogLevel.Warning, Message = "Realtime Database write {Method} {Path} failed; clients stay on REST")]
    private static partial void LogFailed(ILogger logger, Exception exception, string method, string path);

    [LoggerMessage(Level = LogLevel.Debug, Message = "Realtime Database looks down, skipped {Method} {Path}")]
    private static partial void LogCircuitOpen(ILogger logger, string method, string path);
}

/// <summary>OAuth access token of the Admin SDK service account for the RTDB REST API (not used with the emulator).</summary>
internal interface IRealtimeDatabaseCredential
{
    Task<string> GetAccessTokenAsync(CancellationToken cancellationToken);
}

/// <summary>
/// The <c>Firebase:ServiceAccountJson</c> key, or Application Default Credentials. The credential caches the token and
/// refreshes it before it expires.
/// </summary>
internal sealed class GoogleRealtimeDatabaseCredential(IOptions<FirebaseOptions> options) : IRealtimeDatabaseCredential
{
    private static readonly string[] Scopes =
        ["https://www.googleapis.com/auth/firebase.database", "https://www.googleapis.com/auth/userinfo.email"];

    private readonly Lazy<ITokenAccess> _credential = new(() => FirebaseCredentials.Create(options.Value).CreateScoped(Scopes));

    public Task<string> GetAccessTokenAsync(CancellationToken cancellationToken) =>
        _credential.Value.GetAccessTokenForRequestAsync(cancellationToken: cancellationToken);
}
